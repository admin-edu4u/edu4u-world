    function countdown(time)
    {
      var myTimer, timing = time;
      $('.countdown').html(timing+' seconds');
      $('.countdown').show();
      $('.send-otp').hide();
      myTimer = setInterval(function() {
        --timing;
        $('.countdown').html(timing+' seconds');
        sessionStorage.setItem("sms_time", timing);
        if (timing === 0) {
          clearInterval(myTimer);
          $('.countdown').hide();
          $('.send-otp').show();
        }
      }, 1000);
    }

